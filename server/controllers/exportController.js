// Generates a printable, college-branded timetable PDF (server side, using PDFKit).
const PDFDocument = require('pdfkit');
const ClassSection = require('../models/ClassSection');
const Teacher = require('../models/Teacher');
const TimetableSlot = require('../models/TimetableSlot');
const { asyncHandler, HttpError } = require('../middleware/errorHandler');
const { populateSlot } = require('../services/timetableService');
const { DAYS, DAY_LABELS, PERIODS, RECESS } = require('../config/constants');

const NAVY = '#4e1520'; // header and headings (maroon)
const GOLD = '#e0912f'; // accent (marigold)
const LAB = '#e0f0ec';
const THEORY = '#e7eef4';

function drawTimetable(doc, { title, subtitle, slots, cellLine }) {
  const collegeName = process.env.COLLEGE_NAME || 'ClassOptima Institute of Technology';
  const pageW = doc.page.width;
  const margin = 30;

  // Header band
  doc.rect(0, 0, pageW, 62).fill(NAVY);
  doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(18).text(collegeName, margin, 14, { width: pageW - margin * 2, align: 'center' });
  doc.fillColor(GOLD).font('Helvetica').fontSize(10).text('Official Weekly Timetable  |  Generated by ClassOptima', margin, 38, { width: pageW - margin * 2, align: 'center' });
  doc.fillColor(NAVY).font('Helvetica-Bold').fontSize(13).text(title, margin, 76);
  doc.fillColor('#555555').font('Helvetica').fontSize(9).text(subtitle, margin, 94);

  // Grid geometry: day column + 7 periods + recess column
  const columns = [];
  PERIODS.forEach((p) => {
    columns.push({ kind: 'period', period: p });
    if (p.index === RECESS.afterPeriod) columns.push({ kind: 'recess' });
  });
  const top = 112;
  const dayW = 62;
  const recessW = 28;
  const periodW = (pageW - margin * 2 - dayW - recessW) / PERIODS.length;
  const headH = 30;
  const rowH = (doc.page.height - top - headH - 50) / DAYS.length;

  const colX = [];
  let x = margin + dayW;
  columns.forEach((c) => {
    colX.push(x);
    x += c.kind === 'recess' ? recessW : periodW;
  });

  // Header row
  doc.rect(margin, top, pageW - margin * 2, headH).fill('#eef0eb');
  doc.fillColor(NAVY).font('Helvetica-Bold').fontSize(9).text('Day', margin + 6, top + 10);
  columns.forEach((c, i) => {
    if (c.kind === 'recess') return;
    doc.font('Helvetica-Bold').fontSize(8.5).fillColor(NAVY)
      .text(`Period ${c.period.index}`, colX[i], top + 5, { width: periodW, align: 'center' });
    doc.font('Helvetica').fontSize(7.5).fillColor('#666666')
      .text(`${c.period.start} - ${c.period.end}`, colX[i], top + 17, { width: periodW, align: 'center' });
  });

  const slotAt = (day, periodIndex) => slots.find((s) => s.day === day && s.slotIndex === periodIndex);
  const covered = (day, periodIndex) => slots.some((s) => s.day === day && s.slotIndex < periodIndex && s.slotIndex + s.duration > periodIndex);

  const bottom = top + headH + DAYS.length * rowH;
  const recessIdx = columns.findIndex((c) => c.kind === 'recess');

  // Pass 1: row and recess backgrounds
  DAYS.forEach((day, r) => {
    const y = top + headH + r * rowH;
    doc.rect(margin, y, dayW, rowH).fill(r % 2 ? '#f7f8f5' : '#ffffff');
  });
  doc.rect(colX[recessIdx], top + headH, recessW, bottom - top - headH).fill('#eef0eb');

  // Pass 2: grid lines (drawn before the cells so multi-period labs cover them)
  doc.lineWidth(0.5).strokeColor('#cccccc');
  doc.rect(margin, top, pageW - margin * 2, bottom - top).stroke();
  for (let r = 0; r <= DAYS.length; r += 1) {
    doc.moveTo(margin, top + headH + r * rowH).lineTo(pageW - margin, top + headH + r * rowH).stroke();
  }
  colX.forEach((cx) => doc.moveTo(cx, top).lineTo(cx, bottom).stroke());

  // Pass 3: day labels and lecture cells
  DAYS.forEach((day, r) => {
    const y = top + headH + r * rowH;
    doc.fillColor(NAVY).font('Helvetica-Bold').fontSize(9).text(DAY_LABELS[day], margin + 6, y + rowH / 2 - 5);
    columns.forEach((c, i) => {
      if (c.kind === 'recess') return;
      if (covered(day, c.period.index)) return;
      const slot = slotAt(day, c.period.index);
      if (!slot) return;
      const isLab = slot.subject && slot.subject.type === 'Practical/Lab';
      const width = periodW * slot.duration;
      doc.roundedRect(colX[i] + 2, y + 2, width - 4, rowH - 4, 4).fill(isLab ? LAB : THEORY);
      doc.fillColor(NAVY).font('Helvetica-Bold').fontSize(8)
        .text(slot.subject ? slot.subject.name : '-', colX[i] + 5, y + 6, { width: width - 10, height: 20, ellipsis: true });
      doc.fillColor('#333333').font('Helvetica').fontSize(7)
        .text(cellLine(slot), colX[i] + 5, y + 28, { width: width - 10, height: rowH - 32, ellipsis: true });
    });
  });

  doc.save().fillColor('#999999').font('Helvetica-Bold').fontSize(8);
  doc.rotate(-90, { origin: [colX[recessIdx] + recessW / 2, top + headH + (bottom - top - headH) / 2] })
    .text(`LUNCH RECESS  ${RECESS.start} - ${RECESS.end}`, colX[recessIdx] + recessW / 2 - 100, top + headH + (bottom - top - headH) / 2 - 4, { width: 200, align: 'center' });
  doc.restore();

  // Footer
  doc.fillColor('#888888').font('Helvetica').fontSize(7.5)
    .text(`Blue = Theory lecture, Green = Practical / Lab   |   Printed ${new Date().toLocaleString('en-IN', { timeZone: process.env.TIMEZONE || 'Asia/Kolkata' })}`,
      margin, doc.page.height - 32, { width: pageW - margin * 2, align: 'center' });
}

function sendPdf(res, filename, draw) {
  const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margin: 0 });
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);
  doc.pipe(res);
  draw(doc);
  doc.end();
}

// GET /api/v1/export/pdf/:sectionId
exports.sectionPdf = asyncHandler(async (req, res) => {
  const section = await ClassSection.findById(req.params.sectionId).populate('classTeacher', 'name');
  if (!section) throw new HttpError(404, 'Division not found.');
  const filter = { classSection: section._id };
  if (req.user.role !== 'admin') filter.isPublished = true;
  const slots = await populateSlot(TimetableSlot.find(filter));
  const label = `${section.name} - Semester ${section.semester} - Division ${section.section}`;
  sendPdf(res, `Timetable_${section.department.replace(/\s+/g, '')}_Sem${section.semester}_Div${section.section}.pdf`, (doc) =>
    drawTimetable(doc, {
      title: label,
      subtitle: `${section.department}  |  Strength: ${section.studentCount} students${section.classTeacher ? `  |  Class Teacher: ${section.classTeacher.name}` : ''}`,
      slots,
      cellLine: (s) => `${s.teacher ? s.teacher.name : ''}\n${s.classroom ? s.classroom.roomNumber : ''}${s.subject ? `  (${s.subject.code})` : ''}`,
    })
  );
});

// GET /api/v1/export/pdf/teacher/:teacherId  (professors may only export their own)
exports.teacherPdf = asyncHandler(async (req, res) => {
  const teacherId = req.params.teacherId === 'me' ? req.user.teacher : req.params.teacherId;
  if (req.user.role === 'professor' && String(teacherId) !== String(req.user.teacher)) {
    throw new HttpError(403, 'You can only export your own timetable.');
  }
  if (req.user.role === 'student') throw new HttpError(403, 'Students cannot export faculty timetables.');
  const teacher = await Teacher.findById(teacherId);
  if (!teacher) throw new HttpError(404, 'Teacher not found.');
  const filter = { teacher: teacher._id };
  if (req.user.role !== 'admin') filter.isPublished = true;
  const slots = await populateSlot(TimetableSlot.find(filter));
  const hours = slots.reduce((n, s) => n + s.duration, 0);
  sendPdf(res, `Timetable_${teacher.name.replace(/[^a-z0-9]+/gi, '_')}.pdf`, (doc) =>
    drawTimetable(doc, {
      title: `${teacher.name} - ${teacher.designation}`,
      subtitle: `${teacher.department}  |  ${teacher.cabinNumber || ''}  |  Workload: ${hours} / ${teacher.maxHoursPerWeek} hrs per week`,
      slots,
      cellLine: (s) => `${s.classSection ? `${s.classSection.department.split(' ').map((w) => w[0]).join('')} Sem ${s.classSection.semester} Div ${s.classSection.section}` : ''}\n${s.classroom ? s.classroom.roomNumber : ''}`,
    })
  );
});
